import assert from "node:assert/strict";
import { initialEbayStoreRegistry, normalizePartNumber, validateEbayStoreRegistry, routeEbayDraft } from "../dist/service/ebay-store-routing.js";
const initial=initialEbayStoreRegistry();
assert.equal(initial.parts.state,"AUTH_REQUIRED");
assert.equal(initial.toner.state,"UNCONFIGURED");
assert.equal(normalizePartNumber(" dg34-00027d "),"DG34-00027D");
assert.equal(normalizePartNumber(" 1089704352 "),"1089704352");
assert.equal(normalizePartNumber("DG34 00027D"),null);
const parts={...initial,parts:{id:"parts",category:"appliance-part",state:"READY",profileId:"edge-parts",accountFingerprint:"ebay-parts"}};
const toner={...parts,toner:{id:"toner",category:"toner",state:"READY",profileId:"edge-toner",accountFingerprint:"ebay-toner"}};
const item={source:"nellis",title:"BlueStars W10276397 Washer Drain Pump",category:"appliance-part",mpn:"W10276397",inventoryNumber:"1084669345",pickedUp:true,condition:"New"};
assert.deepEqual(validateEbayStoreRegistry(toner),[]);
assert.equal(routeEbayDraft(item).reason,"AUTH_REQUIRED");
const valid=routeEbayDraft(item,parts);
assert.equal(valid.ok,true);
assert.equal(valid.storeId,"parts");
assert.equal(valid.mpn,"W10276397");
assert.equal(valid.idempotencyKey,"nellis:1084669345:parts");
assert.equal(routeEbayDraft(item,parts,new Set([valid.idempotencyKey])).reason,"DUPLICATE_JOB");
assert.equal(routeEbayDraft({...item,pickedUp:false},parts).reason,"NELLIS_PICKED_UP_REQUIRED");
assert.equal(routeEbayDraft({...item,mpn:null},parts).reason,"MPN_REQUIRED_OR_AMBIGUOUS");
assert.equal(routeEbayDraft({...item,inventoryNumber:""},parts).reason,"NELLIS_INVENTORY_REQUIRED");
assert.equal(routeEbayDraft({...item,condition:"Unknown"},parts).reason,"NEW_CONDITION_NOT_VERIFIED");
assert.equal(routeEbayDraft({...item,storeId:"toner"},toner).reason,"STORE_CATEGORY_MISMATCH");
const direct={source:"direct",title:"Whirlpool W10276397 Washer Pump",category:"appliance-part",mpn:"w10276397",inventoryNumber:null,condition:"New"};
assert.equal(routeEbayDraft(direct,parts).ok,true);
assert.equal(routeEbayDraft({...direct,inventoryNumber:"1084669345"},parts).reason,"DIRECT_INPUT_CANNOT_ASSERT_NELLIS_INVENTORY");
const tone={source:"nellis",title:"HP Toner 141X",category:"toner",mpn:"W1410X",inventoryNumber:"123456789",pickedUp:true,condition:"New"};
assert.equal(routeEbayDraft(tone,toner).storeId,"toner");
assert.equal(routeEbayDraft(tone,parts).reason,"AUTH_REQUIRED");
const collision={...toner,toner:{...toner.toner,profileId:"edge-parts"}};
assert.ok(validateEbayStoreRegistry(collision).includes("STORE_PROFILE_REUSED:toner"));
const sameAccount={...toner,toner:{...toner.toner,accountFingerprint:"ebay-parts"}};
assert.ok(validateEbayStoreRegistry(sameAccount).includes("STORE_ACCOUNT_REUSED:toner"));
console.log("EBAY_STORE_ROUTING_REGRESSION_PASS");
