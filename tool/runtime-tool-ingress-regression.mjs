const generation="a".repeat(32);
assert.deepEqual(decodeRuntimeIngressMarker(Buffer.from(generation+"\n")),{state:"quiescing",generation});
assert.deepEqual(decodeRuntimeIngressMarker(Buffer.concat([Buffer.alloc(32,0xe1),Buffer.from("\n")])),{state:"unavailable"});
assert.deepEqual(decodeRuntimeIngressMarker(Buffer.from(generation+"\n\n")),{state:"unavailable"});
let marker={state:"open"};
const gate=createRuntimeToolIngress(()=>marker,true);
const clients=[];
let effects=0,release,entered;
const started=new Promise(r=>entered=r);
const pending=new Promise(r=>release=r);
const config={description:"inert test",inputSchema:z.object({}).strict()};
async function profile(name,handler) {
  const server=new McpServer({name,version:"1"});
  const wrapped=gate.wrap(server);
  wrapped.registerTool("write.fixture.effect",config,handler);
  wrapped.registerTool("read_.system.console.health",config,async()=>({content:[{type:"text",text:JSON.stringify(gate.snapshot())}]}));
  const [ct,st]=InMemoryTransport.createLinkedPair();
  const client=new Client({name:name+"-client",version:"1"});
  await server.connect(st);await client.connect(ct);
  clients.push(client,server);
  return client;
}
const a=await profile("tcp",async()=>{effects++;entered();await pending;return {content:[{type:"text",text:"done"}]};});
const b=await profile("facade",async()=>{effects++;return {content:[{type:"text",text:"done"}]};});
const running=a.callTool({name:"write.fixture.effect",arguments:{}}).catch(()=>null);
await started;
assert.equal(gate.snapshot().activeHandlers,1);
marker={state:"quiescing",generation};
assert.equal(gate.snapshot().drained,false);
const blocked=await b.callTool({name:"write.fixture.effect",arguments:{}});
assert.equal(blocked.isError,true);assert.equal(blocked.structuredContent.status,"RUNTIME_INGRESS_QUIESCED");
assert.equal(effects,1);
const health=await b.callTool({name:"read_.system.console.health",arguments:{}});
assert.equal(JSON.parse(health.content[0].text).activeHandlers,1);
await a.close(); // transport loss is not handler completion
assert.equal(gate.snapshot().activeHandlers,1);
release();await running;
for(let i=0;i<50&&gate.snapshot().activeHandlers;i++)await new Promise(r=>setTimeout(r,5));
assert.deepEqual(gate.snapshot(),{protocol:1,enabled:true,state:"quiescing",generation,activeHandlers:0,drained:true});
marker={state:"unavailable"};
assert.equal((await b.callTool({name:"write.fixture.effect",arguments:{}})).isError,true);
assert.equal(gate.snapshot().drained,false);
marker={state:"open"};
assert.equal((await b.callTool({name:"write.fixture.effect",arguments:{}})).isError,undefined);
assert.equal(effects,2);
await assert.rejects(gate.invoke("write.fixture.error",async()=>{throw Error("fixture")},[]));
