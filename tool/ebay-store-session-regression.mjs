reject({verifiedAtEpochMs:now+1},"SESSION_EVIDENCE_STALE");
reject({endpoint:"http://0.0.0.0:9227/"},"CDP_ENDPOINT_NOT_LOOPBACK");
reject({endpoint:"http://localhost:9227/"},"CDP_ENDPOINT_NOT_LOOPBACK");
reject({url:"https://example.com/"},"EBAY_ORIGIN_INVALID");
